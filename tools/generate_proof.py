def family(p, goal, leaf, fixed=None, hyps=(), extra=(), reset_needs_r=True, true_term=None, kinds=("settle", "renew", "classifier", "hard")):
    """Emit one lemma per event kind. `goal` is written with R and m."""
    hp = "".join(f", {n}: {t}" for n, t in hyps)
    ex = "".join(f", {x}" for x in extra)
    exn = "".join(", " + x.split(":")[0].lstrip("+") for x in extra)
    mp = "" if fixed else "+m: K.ContainmentMode, "
    ma = "" if fixed else "m, "
    fx = {"m": fixed} if fixed else {}
    for k in kinds:
        R = sub(f"K.seal(at, cnt, {INNER[k]})", fx)
        g = sub(goal.replace("R", R).replace("CNT", "cnt"), fx)
        ht = "".join(f", {n}: {sub(t, fx)}" for n, t in hyps)
        vs = [("inn", B)] + ([] if fixed else [("m", M)]) + LV[k]
        lemma(f"{p}_{k}", f"+cfg: K.KernelConfig, inn: Bool, +at: Nat, {mp}+d: Nat, +cnt: Nat{KARG[k][0]}{ex}{ht}", g,
              vs, lambda e, gg: leaf({**e, "m": fixed or e["m"], "kind": k}, gg))
    R = sub(RS, fx)
    g = sub(goal.replace("R", R).replace("CNT", "counter"), fx)
    inn = "Nat.is_lt(at, d)"
    ht = "".join(f", {n}: {sub(sub(t, {'inn': inn}), fx)}" for n, t in hyps)
    ha = "".join(f", {n}" for n, _ in hyps)
    rp = ", r: {acc == False{} : Bool}" if reset_needs_r else ""
    tt = sub(g, {"acc": T})
    term = absurd(tt, no("r")) if reset_needs_r else true_term
    body = (f"  match acc:\n    case True{{}}:\n      {term}\n    case False{{}}:\n"
            f"      {p}_settle(cfg, {inn}, at, {ma}d, counter{exn}{ha})\n")
    out.append(f"\ndef {p}_reset(+cfg: K.KernelConfig, acc: Bool, +at: Nat, {mp}+d: Nat, +counter: Nat, +n: Nat, +ttl: Nat{ex}{ht}{rp}) -> {g}:\n{body}")


def law(name, args, p, m="m", extra=(), hyps=(), reset_r=True):
    """Dispatch a step law over the event constructor."""
    ma = "" if m is None else f"{m}, "
    ex = "".join(", " + x for x in extra)
    def h(hs): return "".join(", " + x for x in hs)
    hy = h(hyps)
    rr = ", r" if reset_r else ""
    reset = f"K.reset_ok({m or '@'}, counter, s, n, f, na, {AT})"
    out.append(f"""
def Laws.{name}({args}):
  match e:
    case K.ClockTick{{+now}}:
      {p}_settle(cfg, {IN}, {AT}, {ma}d, counter{ex}{hy})
    case K.AgentRequest{{+now}}:
      {p}_settle(cfg, {IN}, {AT}, {ma}d, counter{ex}{hy})
    case K.Renew{{+now, +ttl}}:
      {p}_renew(cfg, {IN}, {AT}, {ma}d, counter, ttl{ex}{hy})
    case K.Classifier{{+now, +level}}:
      {p}_classifier(cfg, {IN}, {AT}, {ma}d, counter, level{ex}{hy})
    case K.HardRule{{+now, +level}}:
      {p}_hard(cfg, {IN}, {AT}, {ma}d, counter, level{ex}{hy})
    case K.Reset{{+now, +s, +n, +f, +na, +ttl}}:
      {p}_reset(cfg, {reset}, {AT}, {ma}d, counter, n, ttl{ex}{hy}{rr})
""")


