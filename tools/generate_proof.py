def lemma(name, params, goal, vs, leaf=lambda e, g: Q):
    out.append(f"\ndef {name}({params}) -> {goal}:\n" + nest(vs, lambda e: leaf(e, sub(goal, e))))


# Small model used only to choose proof terms. Bend checks every selected term.
def settled(inn, m):
    if inn == T: return m
    return {RUN: FRZ, RES: FRZ, HOLD: HOLD, FRZ: KILL, KILL: KILL}[m]
def raised(m, l):
    t = LEVEL_MODE[l]
    if m in (RUN, RES): return t
    if m == HOLD: return t if t in (FRZ, KILL) else HOLD
    if m == FRZ: return KILL if t == KILL else FRZ
    return KILL
def cap(l): return LR if l == LR else LH
def result(kind, e, m):
    s = settled(e["inn"], m)
    if kind == "classifier": return raised(s, cap(e["level"]))
    if kind == "hard": return raised(s, e["level"])
    return s


