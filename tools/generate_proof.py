def eq_true(x): return "{%s == True{} : Bool}" % x
def eq_false(x): return "{%s == False{} : Bool}" % x
def no(h): return f"true_is_not_false({h})"
def yes(h): return f"false_is_not_true({h})"
def absurd(goal, proof): return f"Empty.absurd({goal}, {proof})"


def sub(t, env):
    for k, v in env.items():
        t = re.sub(r"(?<![\w.])" + re.escape(k) + r"(?![\w{])", lambda _: v, t)
    return t


def nest(vs, leaf, ind=1, env=None):
    env = env or {}
    p = "  " * ind
    if not vs:
        return "".join(p + l + "\n" for l in leaf(env).split("\n"))
    v, cs = vs[0]
    o = f"{p}match {v}:\n"
    for c in cs:
        o += f"{p}  case {c}:\n" + nest(vs[1:], leaf, ind + 2, {**env, v: c})
    return o


