#!/usr/bin/env python3
"""Generate formal/PROOF.bend. The proofs are exhaustive over finite modes and severity levels."""
from pathlib import Path
M = ["K.ModeRun{}", "K.ModeRestrict{}", "K.ModeFreeze{}", "K.ModeKill{}"]
L = ["K.ToRestrict{}", "K.ToFreeze{}", "K.ToKill{}"]
B = ["True{}", "False{}"]
K_ = ["K.EgressAccess{}", "K.SecretAccess{}"]
def nest(vs, leaf, ind=1, env=None):
    env = env or {}
    p = "  " * ind
    if not vs:
        return "".join(p + l + "\n" for l in leaf(env).split("\n"))
    v, cs = vs[0]
    o = f"{p}match {v}:\n"
    for c in cs:
        o += f"{p}  case {c}:\n" + nest(vs[1:], leaf, ind + 2, {**env, v: c})
    return o

import re
Q = "{==}"
def sub(t, env):
    for k, v in env.items():
        t = re.sub(r"(?<![\w.])" + re.escape(k) + r"(?![\w{])", lambda _: v, t)
    return t
HEAD = """# Proofs of the containment laws. Generated by tools/generate_proof.py.

import Base
import ./kernel.bend as K
import ./LAWS.bend as Laws

def true_motive(b: Bool) -> Type:
  match b:
    case True{}:
      Unit
    case False{}:
      Empty

def false_motive(b: Bool) -> Type:
  match b:
    case True{}:
      Empty
    case False{}:
      Unit

def true_is_not_false(h: {True{} == False{} : Bool}) -> Empty:
  %h : true_motive(_)
  Unit{}

def false_is_not_true(h: {False{} == True{} : Bool}) -> Empty:
  %h : false_motive(_)
  Unit{}

def min_le(t: Nat, +m: Nat) -> {Nat.is_le(Nat.min(t, m), m) == True{} : Bool}:
  match t m:
    case 0n 0n:
      {==}
    case 0n 1n+p:
      {==}
    case 1n+a 0n:
      {==}
    case 1n+a 1n+p:
      min_le(a, p)

def add_mono(now: Nat, -a: Nat, -b: Nat, h: {Nat.is_le(a, b) == True{} : Bool}) -> {Nat.is_le(Nat.add(now, a), Nat.add(now, b)) == True{} : Bool}:
  match now:
    case 0n:
      h
    case 1n+p:
      add_mono(p, a, b, h)
"""
out = [HEAD]
def lemma(name, params, goal, vs, leaf=lambda e, g: Q):
    body = nest(vs, lambda e: leaf(e, sub(goal, e)))
    out.append(f"\ndef {name}({params}) -> {goal}:\n{body}")
S = "K.settle_with(cfg, inn, now, m, d)"
def ev(kind):
    return {
      "settle": S,
      "renew": f"K.renew_after(cfg, now, ttl, {S})",
      "classifier": f"K.raise_after(cfg, now, K.cap_classifier(level), {S})",
      "hard": f"K.raise_after(cfg, now, level, {S})",
    }[kind]
ARG = {"settle": "", "renew": ", ttl: Nat", "classifier": ", level: K.SeverityLevel", "hard": ", level: K.SeverityLevel"}
PASS = {"settle": "", "renew": ", ttl", "classifier": ", level", "hard": ", level"}
LV = {"settle": [], "renew": [], "classifier": [("level", L)], "hard": [("level", L)]}
BASE = "+cfg: K.KernelConfig, inn: Bool, +now: Nat, m: K.ContainmentMode, +d: Nat"
BASEP = "+cfg: K.KernelConfig, inn: Bool, +now: Nat, +m: K.ContainmentMode, +d: Nat"
def for_events(prefix, params, goalf, vs, leaf=lambda e, g: Q, extra="", ):
    for k in ev.__defaults__ or []: pass
    for k in ["settle", "renew", "classifier", "hard"]:
        lemma(f"{prefix}_{k}", params + ARG[k] + extra, goalf(ev(k)), vs(k), leaf)
def dead_true(hyp):
    return lambda e, g: Q if e.get("inn") == "False{}" else f"Empty.absurd({g}, true_is_not_false({hyp}))"
for_events("closed", BASE, lambda t: "{Laws.is_live(Laws.mode_of(%s)) == False{} : Bool}" % t,
           lambda k: [("inn", B), ("m", M)] + LV[k], dead_true("h"), ", h: {inn == False{} : Bool}")
for_events("tight", BASEP, lambda t: "{Laws.rank_at_least(Laws.mode_of(%s), m) == True{} : Bool}" % t,
           lambda k: [("inn", B), ("m", M)] + LV[k])
for_events("killed", "+cfg: K.KernelConfig, inn: Bool, +now: Nat, +d: Nat",
           lambda t: "{Laws.is_kill(Laws.mode_of(%s)) == True{} : Bool}" % t.replace(", m, d)", ", K.ModeKill{}, d)"),
           lambda k: [("inn", B)] + LV[k])
for_events("ordered", BASEP, lambda t: "{Laws.stop_is_ordered(Laws.plan_of(%s), Laws.secrets_gone(m), Laws.egress_gone(m)) == True{} : Bool}" % t,
           lambda k: [("inn", B), ("m", M)] + LV[k])
def noklv(e, g):
    if e.get("inn") == "False{}": return f"Empty.absurd({g}, false_is_not_true(h))"
    if e.get("m") == "K.ModeKill{}": return f"Empty.absurd({g}, true_is_not_false(k))"
    return Q
lemma("classifier_safe", BASE + ", level: K.SeverityLevel, k: {Laws.is_kill(m) == False{} : Bool}, h: {inn == True{} : Bool}",
      "{Laws.is_kill(Laws.mode_of(%s)) == False{} : Bool}" % ev("classifier"), [("inn", B), ("m", M), ("level", L)], noklv)
def bound(e, g):
    if e["inn"] == "True{}" and e["m"] in M[:2]:
        return "add_mono(now, Nat.min(ttl, K.max_lease_of(cfg)), K.max_lease_of(cfg), min_le(ttl, K.max_lease_of(cfg)))"
    return Q
R = ev("renew")
lemma("renew_bound", BASE + ", ttl: Nat",
      "{Laws.implies(Laws.is_live(Laws.mode_of(%s)), Nat.is_le(Laws.deadline_of(%s), Nat.add(now, K.max_lease_of(cfg)))) == True{} : Bool}" % (R, R),
      [("inn", B), ("m", M)], bound)
A = "K.allow_with(inn, m, K.AccessRequest{k, g, b})"
lemma("grant_needed", "inn: Bool, m: K.ContainmentMode, k: K.AccessKind, +g: Bool, b: Bool",
      "{Laws.implies(%s, g) == True{} : Bool}" % A, [("inn", B), ("m", M), ("k", K_), ("g", B), ("b", B)])
out.append("""
def expired_denies(inn: Bool, m: K.ContainmentMode, r: K.AccessRequest, h: {inn == False{} : Bool}) -> {K.allow_with(inn, m, r) == False{} : Bool}:
  match inn:
    case True{}:
      Empty.absurd({K.allow_with(True{}, m, r) == False{} : Bool}, true_is_not_false(h))
    case False{}:
      {==}
""")
def stopped(e, g):
    if e["m"] in M[:2]: return f"Empty.absurd({g}, false_is_not_true(s))"
    return Q
lemma("stopped_lemma", "inn: Bool, m: K.ContainmentMode, k: K.AccessKind, g: Bool, b: Bool, s: {Laws.is_stopped(m) == True{} : Bool}",
      "{K.allow_with(inn, m, K.AccessRequest{k, g, b}) == False{} : Bool}", [("inn", B), ("m", M)], stopped)
lemma("restrict_secret", "inn: Bool, g: Bool, b: Bool",
      "{K.allow_with(inn, K.ModeRestrict{}, K.AccessRequest{K.SecretAccess{}, g, b}) == False{} : Bool}", [("inn", B)])
IN = "Nat.is_lt(now, d)"
def law_events(prefix, tail, call_settle, reset_true, reset_false):
    return f"""  match e:
    case K.ClockTick{{+now}}:
      {prefix}_settle(cfg, {IN}, now, {tail}{call_settle})
    case K.AgentRequest{{+now}}:
      {prefix}_settle(cfg, {IN}, now, {tail}{call_settle})
    case K.Renew{{+now, ttl}}:
      {prefix}_renew(cfg, {IN}, now, {tail}, ttl{call_settle})
    case K.Classifier{{+now, level}}:
      {prefix}_classifier(cfg, {IN}, now, {tail}, level{call_settle})
    case K.HardRule{{+now, level}}:
      {prefix}_hard(cfg, {IN}, now, {tail}, level{call_settle})
    case K.Reset{{+now, signed, ttl}}:
      match signed:
        case True{{}}:
{reset_true}
        case False{{}}:
{reset_false}
"""
def absurd_reset(goal):
    return f"          Empty.absurd({goal}, true_is_not_false(r))"
G_FC = "{Laws.is_live(Laws.mode_of(K.reset_with(cfg, True{}, now, ttl, m, d))) == False{} : Bool}"
out.append("\ndef Laws.fail_closed(cfg, m, d, e, h, r):\n" + law_events("closed", "m, d", ", h", absurd_reset(G_FC), f"          closed_settle(cfg, {IN}, now, m, d, h)"))
G_T = "{Laws.rank_at_least(Laws.mode_of(K.reset_with(cfg, True{}, now, ttl, m, d)), m) == True{} : Bool}"
out.append("\ndef Laws.tighten_only(cfg, m, d, e, r):\n" + law_events("tight", "m, d", "", absurd_reset(G_T), f"          tight_settle(cfg, {IN}, now, m, d)"))
G_K = "{Laws.is_kill(Laws.mode_of(K.reset_with(cfg, True{}, now, ttl, K.ModeKill{}, d))) == True{} : Bool}"
out.append("\ndef Laws.kill_needs_signed_reset(cfg, d, e, r):\n" + law_events("killed", "d", "", absurd_reset(G_K), f"          killed_settle(cfg, {IN}, now, d)"))
out.append("""
def reset_ordered(m: K.ContainmentMode) -> {Laws.stop_is_ordered(K.reset_actions(m), Laws.secrets_gone(m), Laws.egress_gone(m)) == True{} : Bool}:
  match m:
    case K.ModeRun{}:
      {==}
    case K.ModeRestrict{}:
      {==}
    case K.ModeFreeze{}:
      {==}
    case K.ModeKill{}:
      {==}

def Laws.authority_removed_first(cfg, m, d, e):
""" + law_events("ordered", "m, d", "", "          reset_ordered(m)", f"          ordered_settle(cfg, {IN}, now, m, d)"))
out.append(f"""
def Laws.classifier_cannot_kill(cfg, m, d, now, level, k, h):
  classifier_safe(cfg, {IN}, now, m, d, level, k, h)

def Laws.renewal_is_bounded(cfg, m, d, now, ttl):
  renew_bound(cfg, {IN}, now, m, d, ttl)

def Laws.reset_is_bounded(cfg, m, d, now, ttl):
  add_mono(now, Nat.min(ttl, K.max_lease_of(cfg)), K.max_lease_of(cfg), min_le(ttl, K.max_lease_of(cfg)))

def Laws.access_requires_grant(now, m, d, k, g, b):
  grant_needed({IN}, m, k, g, b)

def Laws.expired_lease_denies(now, m, d, r, h):
  expired_denies({IN}, m, r, h)

def Laws.stopped_denies(now, m, d, r, s):
  match r:
    case K.AccessRequest{{k, g, b}}:
      stopped_lemma({IN}, m, k, g, b, s)

def Laws.restrict_denies_secrets(now, d, g, b):
  restrict_secret({IN}, g, b)
""")
RANK = {m: i for i, m in enumerate(M)}
def trans(e, g):
    if RANK[e["a"]] < RANK[e["b"]]: return f"Empty.absurd({g}, false_is_not_true(x))"
    if RANK[e["b"]] < RANK[e["c"]]: return f"Empty.absurd({g}, false_is_not_true(y))"
    return Q
lemma("rank_trans", "+a: K.ContainmentMode, +b: K.ContainmentMode, +c: K.ContainmentMode, x: {Laws.rank_at_least(a, b) == True{} : Bool}, y: {Laws.rank_at_least(b, c) == True{} : Bool}",
      "{Laws.rank_at_least(a, c) == True{} : Bool}", [("a", M), ("b", M), ("c", M)], trans)
lemma("rank_refl", "+m: K.ContainmentMode", "{Laws.rank_at_least(m, m) == True{} : Bool}", [("m", M)])
out.append("""
def tighten_state(+cfg: K.KernelConfig, +c: K.ControlState, +e: K.ControlEvent, r: {Laws.is_signed_reset(e) == False{} : Bool}) -> {Laws.rank_at_least(Laws.state_mode(Laws.control_of(K.step(cfg, c, e))), Laws.state_mode(c)) == True{} : Bool}:
  match c:
    case K.ControlState{+m, +d}:
      Laws.tighten_only(cfg, m, d, e, r)

def Laws.no_sequence_lowers_containment(es, cfg, c, u):
  match es:
    case Nil{}:
      rank_refl(Laws.state_mode(c))
    case Con{+e, +t}:
      (ue, ut) = u
      +next = Laws.control_of(K.step(cfg, c, e))
      rank_trans(Laws.state_mode(Laws.replay(t, cfg, next)), Laws.state_mode(next), Laws.state_mode(c), Laws.no_sequence_lowers_containment(t, cfg, next, ut), tighten_state(cfg, c, e, ue))
""")
Path(__file__).resolve().parents[1].joinpath("formal/PROOF.bend").write_text("".join(out))
